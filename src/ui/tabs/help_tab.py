"""使用说明 Tab — 纯静态文本。"""

import dearpygui.dearpygui as dpg


def build() -> None:
    """构建使用说明 tab（仅调用一次）。"""
    with dpg.tab(label="使用说明", tag="tab_help"):
        dpg.add_text(
            "第一步，添加文件\n"
            "第二步，设置时间\n"
            "第三步，填写导出设置\n"
            "第四步，点击导出按钮\n"
            "\n"
            "如果不知道有些参数有什么用可以不填，应用会使用默认的设置\n"
            "\n"
            "小技巧：\n"
            '- 起止时间里的空格会被替换为":"，例如"01 20"会被替换为"01:20"\n'
            '- 起止时间如果是"开头"或者"结尾"，则不会对开始时间和结尾时间进行选择',
            wrap=460,
        )
